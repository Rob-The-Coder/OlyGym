/* ============================================================================
   OlyGym — the same eight M3 colour schemes, for the native app.

   Run:  node scripts/design/m3-scheme-kotlin.mjs

   It imports scheme() and SEEDS from its CSS sibling, so the two themes cannot
   drift: one seed list, one tone rule. Writes
   native/app/src/main/java/olygym/app/ui/theme/Scheme.kt — generated, do not
   hand-edit. ui/theme/Theme.kt turns these roles into a Compose ColorScheme.
   ============================================================================ */
import { mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { SEEDS, DEFAULT_ACCENT, scheme } from './m3-scheme.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(HERE, '../../native/app/src/main/java/olygym/app/ui/theme/Scheme.kt')

// Role name in Kotlin -> key on the object scheme() returns.
const ROLES = [
  ['surface', 'surface'],
  ['containerLow', 'low'],
  ['container', 'container'],
  ['containerHigh', 'high'],
  ['containerHighest', 'highest'],
  ['onSurface', 'onSurface'],
  ['onSurfaceVariant', 'onSurfaceVariant'],
  ['onSurfaceDisabled', 'onSurfaceDisabled'],
  ['hairline', 'hairline'],
  ['outline', 'outline'],
  ['outlineVariant', 'outlineVariant'],
  ['primary', 'primary'],
  ['onPrimary', 'onPrimary'],
  ['primaryContainer', 'primaryContainer'],
  ['onPrimaryContainer', 'onPrimaryContainer'],
  ['error', 'error'],
  ['onError', 'onError'],
  ['errorContainer', 'errorContainer'],
  ['onErrorContainer', 'onErrorContainer'],
]

const argb = hex => '0xFF' + hex.replace('#', '').toUpperCase()

const roles = (seed, theme) => {
  const s = scheme(seed, theme)
  return ROLES.map(([name, key]) => `${name} = ${argb(s[key])},`).map(l => '            ' + l).join('\n')
}

const accents = Object.entries(SEEDS).map(([name, seed]) => `    "${name}" to AccentScheme(
        dark = Roles(
${roles(seed, 'dark')}
        ),
        light = Roles(
${roles(seed, 'light')}
        ),
    ),`).join('\n')

const file = `// GENERATED by scripts/design/m3-scheme-kotlin.mjs from the same seeds as
// frontend/src/m3.tokens.css. Do not edit by hand: change a seed in
// scripts/design/m3-scheme.mjs and re-run both generators.
package olygym.app.ui.theme

/** The colour roles OlyGym uses, as ARGB. One set per theme, one pair per accent. */
internal data class Roles(
    val surface: Long,
    val containerLow: Long,
    val container: Long,
    val containerHigh: Long,
    val containerHighest: Long,
    val onSurface: Long,
    val onSurfaceVariant: Long,
    val onSurfaceDisabled: Long,
    val hairline: Long,
    val outline: Long,
    val outlineVariant: Long,
    val primary: Long,
    val onPrimary: Long,
    val primaryContainer: Long,
    val onPrimaryContainer: Long,
    val error: Long,
    val onError: Long,
    val errorContainer: Long,
    val onErrorContainer: Long,
)

internal data class AccentScheme(val dark: Roles, val light: Roles)

/** Every accent the picker offers. An unknown stored accent falls back to DEFAULT_ACCENT. */
internal val SCHEMES: Map<String, AccentScheme> = mapOf(
${accents}
)
`

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, file)
console.log('wrote ' + OUT + ' (' + file.split('\n').length + ' lines)')

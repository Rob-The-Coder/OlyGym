#!/usr/bin/env node
/**
 * Build frontend/src/lib/exercises-data.js — the OlyGym exercise catalogue.
 *
 *   node scripts/oly-catalogue/build-oly-catalogue.mjs           # write the catalogue
 *   node scripts/oly-catalogue/build-oly-catalogue.mjs --check   # fail if it is out of date
 *
 * Two inputs, both in this directory:
 *
 *   catalyst-exercises.csv  the Catalyst Athletics exercise list (name, category, youtube url,
 *                           catalyst page, description). Upstream data: it changes by
 *                           re-scraping, never by hand.
 *   exercise-tags.json      this fork's curated per-exercise metadata, keyed by catalogue id:
 *                           `eq` (equipment — it decides the bar weight and whether the app asks
 *                           for a weight at all) and `tg`/`sm` (muscle tags, which the muscle map
 *                           and the recovery model read). A missing `tg`/`sm` stays missing.
 *
 * The id is `wl` + the Catalyst exercise-page id from the URL, so every entry stays traceable to
 * the page it came from (`src`). Entries are written in the Catalyst section order, and within a
 * family in the CSV's own order.
 *
 * Adding an exercise means re-scraping the CSV and adding its tags to the sidecar; the build fails
 * loudly on either half missing, and `--check` is what CI runs.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..', '..')
const CSV = join(HERE, 'catalyst-exercises.csv')
const TAGS = join(HERE, 'exercise-tags.json')
const OUT = join(ROOT, 'frontend', 'src', 'lib', 'exercises-data.js')

// The order the catalogue is written in — the order the Catalyst section pages list exercises in.
// A category the sidecar has no place for is an error rather than a silent "somewhere at the end":
// muscles.js needs a BY_BODYPART fallback for every one of them.
const FAMILIES = [
  'Snatch', 'Clean', 'Jerk', 'General Exercises', 'Trunk (Ab & Back)', 'Jumping & Plyometrics',
  'Accessory - Lower/Whole Body', 'Accessory - Prep & Prehab', 'Accessory - Upper Body', 'Carries',
]

const HEADER = `// Auto-generated by scripts/oly-catalogue/build-oly-catalogue.mjs — do not edit by hand.
// id = "wl" + Catalyst Athletics exercise-page id (stable, unique, traceable via \`src\`).
// eq/tg/sm live in scripts/oly-catalogue/exercise-tags.json: equipment drives the bar weight and
// the bodyweight model, the muscle tags drive the muscle map. bp carries the Catalyst movement
// category and drives both the Library filter chips and the BY_BODYPART fallback in muscles.js
// for entries with no specific tg/sm match.
export const EXDB = [`

/** RFC-4180-ish reader: quoted fields, doubled quotes, CRLF or LF. */
function parseCSV(text) {
  const rows = []
  let row = [], field = '', quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++ } else quoted = false
      } else field += c
    } else if (c === '"') quoted = true
    else if (c === ',') { row.push(field); field = '' }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = '' }
    else if (c !== '\r') field += c
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row) }
  return rows
}

/** The catalogue's own compact one-entry-per-line JSON: `, ` between fields and array items. */
const fmt = value => {
  if (Array.isArray(value)) return '[' + value.map(fmt).join(', ') + ']'
  if (value && typeof value === 'object') {
    return '{' + Object.entries(value).map(([k, v]) => JSON.stringify(k) + ': ' + fmt(v)).join(', ') + '}'
  }
  return JSON.stringify(value)
}

function readInputs() {
  const lines = readFileSync(CSV, 'utf8').split('\n').filter(l => l.trim() && !l.trimStart().startsWith('#'))
  const rows = parseCSV(lines.join('\n'))
  const header = rows.shift().map(h => h.trim())
  const column = Object.fromEntries(header.map((h, i) => [h, i]))
  for (const need of ['name', 'category', 'youtube_url', 'catalyst_url', 'description']) {
    if (column[need] === undefined) throw new Error(`the CSV has no "${need}" column (has: ${header.join(', ')})`)
  }

  const tags = JSON.parse(readFileSync(TAGS, 'utf8'))
  const entries = rows.map((r, i) => {
    const src = String(r[column.catalyst_url] || '').trim()
    const m = /\/exercise\/(\d+)\//.exec(src)
    if (!m) throw new Error(`CSV row ${i + 2}: no Catalyst exercise id in "${src}"`)
    const bp = String(r[column.category] || '').trim()
    if (!FAMILIES.includes(bp)) throw new Error(`CSV row ${i + 2}: unknown category "${bp}" — add it to FAMILIES and to BY_BODYPART`)
    const name = String(r[column.name] || '').trim()
    const desc = String(r[column.description] || '').trim()
    return { id: 'wl' + m[1], n: name.toLowerCase(), bp, desc, yt: String(r[column.youtube_url] || '').trim(), src }
  })

  const seen = new Set()
  for (const e of entries) {
    if (seen.has(e.id)) throw new Error(`two CSV rows share the id ${e.id}`)
    seen.add(e.id)
    if (!tags[e.id]) throw new Error(`${e.id} (${e.n}) has no entry in exercise-tags.json`)
  }
  const orphans = Object.keys(tags).filter(id => !seen.has(id))
  if (orphans.length) console.warn(`warning: exercise-tags.json has ${orphans.length} id(s) no longer in the CSV: ${orphans.join(', ')}`)

  const rank = new Map(FAMILIES.map((f, i) => [f, i]))
  const ordered = entries
    .map((e, i) => ({ e, i }))
    .sort((a, b) => rank.get(a.e.bp) - rank.get(b.e.bp) || a.i - b.i)
    .map(x => x.e)

  return { tags, ordered }
}

function build() {
  const { tags, ordered } = readInputs()
  const lines = ordered.map(e => {
    const t = tags[e.id]
    const out = { id: e.id, n: e.n, bp: e.bp, eq: t.eq, desc: e.desc, st: [e.desc] }
    if (t.tg !== undefined) out.tg = t.tg
    if (t.sm !== undefined) out.sm = t.sm
    out.yt = e.yt
    out.src = e.src
    return '  ' + fmt(out) + ','
  })
  return { body: [HEADER, ...lines, ']', ''].join('\n'), count: ordered.length }
}

const { body, count } = build()

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current === body) {
    console.log(`exercises-data.js in sync (${count} exercises).`)
    process.exit(0)
  }
  const a = current.split('\n'), b = body.split('\n')
  const at = a.findIndex((line, i) => line !== b[i])
  console.error('exercises-data.js is out of date — run: node scripts/oly-catalogue/build-oly-catalogue.mjs')
  if (at >= 0) console.error(`  first difference on line ${at + 1}\n    file: ${(a[at] || '').slice(0, 140)}\n    new : ${(b[at] || '').slice(0, 140)}`)
  console.error(`  lines: file ${a.length}, rebuilt ${b.length}`)
  process.exit(1)
}

writeFileSync(OUT, body)
console.log(`Wrote ${OUT.slice(ROOT.length + 1)} — ${count} exercises.`)
